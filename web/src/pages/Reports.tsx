import { recentRuns } from '@/lib/demo-data'
import Badge from '@/components/Badge'
import { useDocumentTitle } from '@/lib/hooks'
import { useToast } from '@/components/Toast'
import { downloadJsonFile } from '@/lib/export'
import styles from './Reports.module.css'

const REPORT_FILES = recentRuns.map(r => ({
  ...r,
  filename: `${r.id}.md`,
  size: `${Math.floor(12 + Math.random() * 40)} KB`,
}))

export default function Reports() {
  useDocumentTitle('Evaluation Reports | Secure Gen')
  const { showToast } = useToast()

  const handlePrint = () => {
    window.print()
  }

  const handleDownloadJson = (r: typeof REPORT_FILES[0]) => {
    downloadJsonFile(r, `${r.id}.json`)
    showToast(`Downloaded ${r.id}.json`, 'success')
  }

  const handleDownloadMd = (r: typeof REPORT_FILES[0]) => {
    const mdContent = `# Benchmark Report: ${r.id}

- Date: ${r.date}
- Type: ${r.type}
- Total Tasks: ${r.tasks}
- Models Evaluated: ${r.models}
- Average Security Score: ${r.avg_score}%

Generated by Secure Gen.
`
    const blob = new Blob([mdContent], { type: 'text/markdown' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = r.filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
    showToast(`Downloaded ${r.filename}`, 'success')
  }

  return (
    <div className={styles.root}>
      <div className={styles.pageHeader}>
        <div className="container">
          <div className={styles.headerActions}>
            <div>
              <h1 className={styles.title}>Reports</h1>
              <p className={styles.subtitle}>Generated reports from benchmark and attack runs. Download as Markdown, JSON, or print to PDF.</p>
            </div>
            <button type="button" onClick={handlePrint} className={styles.printBtn}>
              <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <polyline points="6 9 6 2 18 2 18 9"/>
                <path d="M6 18H4a2 2 0 0 1-2-2v-5a2 2 0 0 1 2-2h16a2 2 0 0 1 2 2v5a2 2 0 0 1-2 2h-2"/>
                <rect x="6" y="14" width="12" height="8"/>
              </svg>
              <span>Print to PDF</span>
            </button>
          </div>
        </div>
      </div>

      <div className={styles.body}>
        <div className="container">
          <div className={styles.howTo}>
            <h2 className={styles.howTitle}>Generate a report via CLI</h2>
            <div className={styles.codeBlock}>
              <pre className={styles.pre}>
                <code>{`# Run a benchmark and generate a report
securegen benchmark run --dataset datasets/security_tasks/cve_triage.json \\
  --model openai:gpt-4o --model anthropic:claude-3-5-sonnet

securegen report generate --run runs/bench_cve_triage.json --format md`}</code>
              </pre>
            </div>
          </div>

          <div className={styles.tableSection}>
            <h2 className={styles.sectionLabel}>Available reports</h2>
            <div className={styles.table}>
              <div className={`${styles.row} ${styles.thead}`}>
                <span>Run ID</span>
                <span>Date</span>
                <span>Type</span>
                <span>Tasks</span>
                <span>Avg Score</span>
                <span>Download</span>
              </div>
              {REPORT_FILES.map(r => (
                <div key={r.id} className={styles.row}>
                  <div>
                    <div className={styles.runId}>{r.id}</div>
                    <div className={styles.filename}>{r.filename}</div>
                  </div>
                  <span className={styles.muted}>{r.date}</span>
                  <Badge variant={r.type === 'attack' ? 'error' : 'teal'}>{r.type}</Badge>
                  <span>{r.tasks}</span>
                  <span className={styles.score}>{r.avg_score}%</span>
                  <div className={styles.downloadLinks}>
                    <button
                      type="button"
                      className={styles.downloadLink}
                      onClick={() => handleDownloadMd(r)}
                      title="Download Markdown report"
                    >
                      MD
                    </button>
                    <button
                      type="button"
                      className={styles.downloadLink}
                      onClick={() => handleDownloadJson(r)}
                      title="Download JSON report"
                    >
                      JSON
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>

          <div className={styles.calloutSection}>
            <div className={styles.calloutCard}>
              <div className={styles.calloutContent}>
                <h3 className={styles.calloutTitle}>Share results publicly</h3>
                <p className={styles.calloutText}>Export your run as JSON and open a pull request to the dataset repository to contribute findings to the community.</p>
              </div>
              <a
                href="https://github.com/RuchitAgrawal/Secure-Gen"
                target="_blank"
                rel="noopener noreferrer"
                className={styles.calloutCta}
              >
                Contribute findings
              </a>
            </div>
          </div>
        </div>
      </div>
    </div>
  )
}
